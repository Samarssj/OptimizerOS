/**
 * Unescapes literal \n, normalizes line breaks, and cleans markdown wrappers so that
 * the full multi-line code is always rendered with accurate line counts.
 */
export function normalizeFullSourceCode(codeStr: string): string {
  if (!codeStr || typeof codeStr !== 'string') return '';
  let normalized = codeStr;

  // Unescape literal \n or \r\n if the AI output contained raw escaped characters
  if (normalized.includes('\\n') && !normalized.includes('\n')) {
    normalized = normalized.replace(/\\r\\n/g, '\n').replace(/\\n/g, '\n').replace(/\\t/g, '\t');
  }

  // Strip wrapping markdown code fences if present (e.g. ```typescript ... ```)
  if (normalized.trim().startsWith('```')) {
    normalized = normalized.trim().replace(/^```[a-zA-Z0-9_-]*\s*\n?/, '').replace(/\n?```\s*$/, '');
  }

  return normalized;
}

/**
 * Robust clipboard copy function supporting modern Clipboard API with
 * seamless fallback to textarea execCommand for iframe and mobile sandboxes.
 */
export async function copyToClipboard(text: string): Promise<boolean> {
  if (!text) return false;
  const cleanText = normalizeFullSourceCode(text);

  // 1. Try modern navigator.clipboard
  try {
    if (navigator.clipboard && typeof navigator.clipboard.writeText === 'function') {
      await navigator.clipboard.writeText(cleanText);
      return true;
    }
  } catch (err) {
    console.warn('[Clipboard] navigator.clipboard.writeText unavailable or restricted in iframe:', err);
  }

  // 2. Fallback using temporary textarea
  try {
    const textArea = document.createElement('textarea');
    textArea.value = cleanText;
    textArea.style.position = 'fixed';
    textArea.style.left = '-999999px';
    textArea.style.top = '-999999px';
    textArea.style.opacity = '0';
    textArea.setAttribute('readonly', '');
    document.body.appendChild(textArea);
    textArea.focus();
    textArea.select();
    const successful = document.execCommand('copy');
    document.body.removeChild(textArea);
    return successful;
  } catch (err) {
    console.error('[Clipboard] execCommand copy fallback failed:', err);
    return false;
  }
}

/**
 * Generates a unified git-compatible patch/diff string.
 */
export function generateGitDiff(originalCode: string, optimizedCode: string, filename = 'code.src'): string {
  const origLines = originalCode.split('\n');
  const optLines = optimizedCode.split('\n');
  
  let diffText = `--- a/${filename}\n+++ b/${filename}\n@@ -1,${origLines.length} +1,${optLines.length} @@\n`;
  
  // Simple representation
  origLines.forEach((l) => {
    diffText += `-${l}\n`;
  });
  optLines.forEach((l) => {
    diffText += `+${l}\n`;
  });

  return diffText;
}
