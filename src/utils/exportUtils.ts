/**
 * Maps a programming language name to its standard file extension.
 */
export function getLanguageExtension(language: string): string {
  const l = (language || '').toLowerCase().trim();
  if (l.includes('typescript') || l === 'ts') return 'ts';
  if (l.includes('tsx')) return 'tsx';
  if (l.includes('javascript') || l === 'js') return 'js';
  if (l.includes('jsx')) return 'jsx';
  if (l.includes('python') || l === 'py') return 'py';
  if (l.includes('c++') || l.includes('cpp')) return 'cpp';
  if (l.includes('c#') || l.includes('cs') || l.includes('csharp')) return 'cs';
  if (l.includes('c') && !l.includes('css') && !l.includes('clojure')) return 'c';
  if (l.includes('java') && !l.includes('script')) return 'java';
  if (l.includes('rust') || l === 'rs') return 'rs';
  if (l.includes('go') || l.includes('golang')) return 'go';
  if (l.includes('sql') || l.includes('postgres') || l.includes('mysql')) return 'sql';
  if (l.includes('php')) return 'php';
  if (l.includes('ruby') || l.includes('rb')) return 'rb';
  if (l.includes('swift')) return 'swift';
  if (l.includes('kotlin') || l.includes('kt')) return 'kt';
  if (l.includes('scala')) return 'scala';
  if (l.includes('bash') || l.includes('sh') || l.includes('shell')) return 'sh';
  if (l.includes('html')) return 'html';
  if (l.includes('css')) return 'css';
  if (l.includes('json')) return 'json';
  if (l.includes('yaml') || l.includes('yml')) return 'yaml';
  return 'txt';
}

/**
 * Triggers a file download on the client machine.
 */
export function downloadFile(content: string, filename: string, mimeType = 'text/plain;charset=utf-8') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);
  URL.revokeObjectURL(url);
}

